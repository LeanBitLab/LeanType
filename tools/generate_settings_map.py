#!/usr/bin/env python3
"""Generate the settings map in docs/FEATURES.md from the settings code, and check doc paths.

The map (screen graph plus the settings on each screen) is built from:
- settings/SettingsNavHost.kt: which screen opens which (navController.navigate calls),
- navigateTo(SettingsDestination.X) calls inside screen files,
- the ordered `items` lists of each screen (category headers and setting keys),
- Setting(context, KEY, R.string.title) definitions and the base strings.xml.

Usage:
  python3 tools/generate_settings_map.py           rewrite the map section in docs/FEATURES.md
  python3 tools/generate_settings_map.py --check   exit 1 if the map is stale or a doc path
                                                   ("Settings → A → B") names no existing screen/setting
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETTINGS = ROOT / "app/src/main/java/helium314/keyboard/settings"
STRINGS = ROOT / "app/src/main/res/values/strings.xml"
FEATURES = ROOT / "docs/FEATURES.md"
DOCS = [ROOT / "README.md", FEATURES]
START = "<!-- SETTINGS_MAP:START (generated by tools/generate_settings_map.py, do not edit by hand) -->"
END = "<!-- SETTINGS_MAP:END -->"

# screens whose title is not a plain `title = stringResource(...)` in their composable
TITLE_OVERRIDES = {
    "AppQuirks": "app_quirks_title",
    "BackgroundServices": "background_services_title",
    "Dictionaries": "dictionary_settings_category",
    "Gif": "gif_settings_title",
    "Sound": "sound_packs_title",
    "OfflineVoice": "voice_input_title",
    "OCR": "ocr_title",
    "Translation": "translation_settings_title",
    "Handwriting": "libraries_hub_handwriting_title",
    "Cjk": "cjk_settings_title",
    "Storage": "libraries_storage_cache_title",
    "TextExpander": "text_expander_title",
    "Layouts": "settings_screen_secondary_layouts",
    "PersonalDictionaries": "edit_personal_dictionary",
    "BlockedWords": "edit_blocked_words",
    "CustomAIKeys": "custom_ai_keys_title",
}
# screens not worth listing (dialogs/editors reached from lists, duplicates)
SKIP = {"Settings", "CustomAIKeyConfig", "PersonalDictionary", "ColorsNight", "Subtype", "LanguagesList"}


def load_strings():
    text = STRINGS.read_text(encoding="utf-8")
    out = {}
    for name, value in re.findall(r'<string name="(\w+)"[^>]*>(.*?)</string>', text, re.S):
        if "@string/" in value:
            continue
        out[name] = html.unescape(re.sub(r"\\(.)", r"\1", value)).strip()
    return out


def block_after(text, start):
    """Text of the balanced (...) block starting at the first '(' at or after start."""
    i = text.index("(", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "(":
            depth += 1
        elif text[j] == ")":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    return text[i + 1:]


def expression_after(text, i):
    """A Kotlin call expression starting at i, e.g. `remember(a) { buildList { ... } }`."""
    m = re.match(r"[\w.]*\s*", text[i:])
    j = i + m.end()
    out_start = j
    while j < len(text) and text[j] in "({":
        depth = 0
        for k in range(j, len(text)):
            if text[k] in "({":
                depth += 1
            elif text[k] in ")}":
                depth -= 1
                if depth == 0:
                    break
        j = k + 1
        while j < len(text) and text[j] in " \t\n":
            j += 1
    return text[out_start:j]


def build():
    S = load_strings()
    kt = {f: f.read_text(encoding="utf-8") for f in SETTINGS.rglob("*.kt")}
    defre = re.compile(r"Setting\(\s*context,\s*([\w.]+),\s*R\.string\.(\w+)")
    key_title = {}
    for t in kt.values():
        for k, s in defre.findall(t):
            if s in S:
                key_title.setdefault(k.split(".")[-1], S[s])
    fun_file = {}
    for f, t in kt.items():
        for fn in re.findall(r"^fun (\w+)\(", t, re.M):
            fun_file[fn] = f

    nav = kt[SETTINGS / "SettingsNavHost.kt"]
    dest_fun, edges = {}, {}
    parts = re.split(r"composable\(SettingsDestination\.(\w+)", nav)
    for dest, body in zip(parts[1::2], parts[2::2]):
        m = re.search(r"(\w+Screen)\(", body)
        if m and dest not in dest_fun:
            dest_fun[dest] = m[1]
        edges.setdefault(dest, [])
        for child in re.findall(r"navigate\(SettingsDestination\.(\w+)", body):
            if child not in edges[dest]:
                edges[dest].append(child)

    def file_of(dest):
        return fun_file.get(dest_fun.get(dest, ""))

    for dest in list(dest_fun):
        f = file_of(dest)
        if not f:
            continue
        for child in re.findall(r"navigateTo\(SettingsDestination\.(\w+)\)", kt[f]):
            if child != dest and child not in edges[dest]:
                edges[dest].append(child)

    def title(dest):
        if dest in TITLE_OVERRIDES and TITLE_OVERRIDES[dest] in S:
            return S[TITLE_OVERRIDES[dest]]
        f = file_of(dest)
        if f:
            t = kt[f]
            i = t.find(f"fun {dest_fun[dest]}(")
            m = re.search(r"title = stringResource\(R\.string\.(\w+)\)", t[i:])
            if m:
                return S.get(m[1], m[1])
        return dest

    def items(dest):
        """Ordered (category, [settings]) of a screen: its `items`/`settings` list, then other named rows."""
        f = file_of(dest)
        if not f:
            return []
        t = kt[f]
        # the screen composable plus the private composables of its file (e.g. flavor variants)
        bodies = []
        for m in re.finditer(r"^(private )?fun (\w+)\(", t, re.M):
            if m[2] == dest_fun[dest] or (m[1] and "Preview" not in m[2]):
                end = t.find("\nfun ", m.end())
                nxt = t.find("\nprivate fun ", m.end())
                end = min(e for e in (end, nxt, len(t)) if e > 0)
                bodies.append(t[m.start():end])
        groups, seen = [], set()
        for body in bodies:
            for m in re.finditer(r"\b(?:val items|settings)\s*=\s*", body):
                blk = expression_after(body, m.end())
                toks = re.findall(r"R\.string\.(settings_category_\w+)|(?:Settings|SettingsWithoutKey)\.(\w+)", blk)
                cur = ["", []]
                for cat, key in toks:
                    if cat:
                        if cur[1]:
                            groups.append(cur)
                        cur = [S.get(cat, cat), []]
                    elif key in key_title and key_title[key] not in seen:
                        seen.add(key_title[key])
                        cur[1].append(key_title[key])
                if cur[1]:
                    groups.append(cur)
            # rows and cards drawn directly (not Setting objects)
            extra = []
            # preference composables, e.g. LanguagePackPreference: their first stringResource is the row name
            for fn in re.findall(r"\b(\w+Preference)\(", body):
                pf = fun_file.get(fn)
                if pf and "/preferences/" in str(pf):
                    pt = kt[pf][kt[pf].find(f"fun {fn}("):]
                    m2 = re.search(r"stringResource\(R\.string\.(\w+)\)", pt)
                    if m2 and S.get(m2[1]) and S[m2[1]] not in seen:
                        seen.add(S[m2[1]])
                        extra.append(S[m2[1]])
            for sid in re.findall(r"(?:name|title) = stringResource\(R\.string\.(\w+)\)|PreferenceCategory\(stringResource\(R\.string\.(\w+)\)", body):
                sid = sid[0] or sid[1]
                label = S.get(sid)
                if label and label not in seen and label != title(dest) and len(label) <= 60:
                    seen.add(label)
                    extra.append(label)
            if "LayoutType.entries" in body:  # one row per secondary layout type
                lt = (ROOT / "app/src/main/java/helium314/keyboard/latin/utils/LayoutType.kt").read_text(encoding="utf-8")
                for sid in re.findall(r"R\.string\.(\w+)", lt)[1:]:
                    if S.get(sid) and S[sid] not in seen:
                        seen.add(S[sid])
                        extra.append(S[sid])
            if extra:
                groups.append(["", extra])
        return groups

    # main screen: groups and their entries, in the order of MainSettingsScreen
    main = kt[fun_file["MainSettingsScreen"]]
    title_dest = {}
    for dest in edges.get("Settings", []) + ["TextExpander"]:
        title_dest[title(dest)] = dest
    groups, cur = [], None
    for gid, sid in re.findall(r"R\.string\.(settings_group_\w+)|name = stringResource\(R\.string\.(\w+)\)", main):
        if gid:
            cur = [S.get(gid, gid), []]
            groups.append(cur)
        elif cur is not None and S.get(sid) in title_dest:
            d = title_dest[S[sid]]
            if d not in cur[1]:
                cur[1].append(d)
    return {"groups": groups, "edges": edges, "title": title, "items": items}


def render(model):
    title, edges, items = model["title"], model["edges"], model["items"]
    out = [START, "", "```mermaid", "graph LR"]
    out.append('  S(["Settings"])')
    seen, order = set(), []

    def nid(d):
        return "n_" + d

    def walk(d, parent_path):
        if d in seen or d in SKIP:
            return
        seen.add(d)
        path = parent_path + [title(d)]
        order.append((d, path))
        for c in edges.get(d, []):
            if c not in seen and c not in SKIP:
                out.append(f'  {nid(d)} --> {nid(c)}["{title(c)}"]')
                walk(c, path)

    for gi, (gname, dests) in enumerate(model["groups"]):
        g = f"g{gi}"
        out.append(f'  S --> {g}{{{{"{gname}"}}}}')
        for d in dests:
            out.append(f'  {g} --> {nid(d)}["{title(d)}"]')
            walk(d, [])
    out += ["```", ""]
    for d, path in order:
        groups = items(d)
        count = sum(len(s) for _, s in groups)
        label = "Settings → " + " → ".join(path)
        if not groups:
            out.append(f"- **{label}**")
            continue
        out.append(f"<details><summary><b>{label}</b> ({count})</summary>")
        out.append("")
        for cat, sets in groups:
            out.append(f"- {'**' + cat + '**: ' if cat else ''}{', '.join(sets)}")
        out.append("")
        out.append("</details>")
    out += ["", END]
    return "\n".join(out)


def known_labels(model):
    """Map screen title -> set of labels allowed after it in a path."""
    title, edges, items = model["title"], model["edges"], model["items"]
    allowed = {}
    for d in edges:
        labels = {title(c).lower() for c in edges.get(d, [])}
        for cat, sets in items(d):
            labels |= {cat.lower()} | {s.lower() for s in sets}
        allowed.setdefault(title(d).lower(), set()).update(labels)
    top = {title(d).lower() for _, ds in model["groups"] for d in ds}
    return top, allowed


def check_paths(model):
    top, allowed = known_labels(model)
    bad = []
    pat = re.compile(r"\*\*Settings\s*(?:→|->)\s*([^*\n]+)\*\*|`((?:[A-Z][^`>\n]*? > )+[^`\n]+)`|\*\*([A-Z][^*\n]*?(?:→|->)[^*\n]+)\*\*")
    for doc in DOCS:
        for n, line in enumerate(doc.read_text(encoding="utf-8").splitlines(), 1):
            if START in line:
                break  # the generated map itself
            for m in pat.finditer(line):
                segs = [s.strip() for s in re.split(r"→|->| > ", m[1] or m[2] or m[3]) if s.strip()]
                if segs and segs[0] == "Settings":
                    segs = segs[1:]
                if not segs or (not m[1] and segs[0].lower() not in top):
                    continue  # a backtick path that is not a settings path (e.g. a key sequence)
                prev, ok = None, True
                for s in segs:
                    s_l = s.lower()
                    if prev is None:
                        ok = s_l in top
                    else:
                        ok = s_l in allowed.get(prev, set())
                    if not ok:
                        bad.append(f"{doc.relative_to(ROOT)}:{n}: '{s}' in '{' → '.join(segs)}'")
                        break
                    prev = s_l if s_l in allowed else prev
    return bad


def main():
    model = build()
    section = render(model)
    text = FEATURES.read_text(encoding="utf-8")
    if START not in text:
        sys.exit(f"{FEATURES.relative_to(ROOT)} has no settings map markers")
    current = text[text.index(START):text.index(END) + len(END)]
    if "--check" in sys.argv:
        problems = []
        if current != section:
            problems.append("settings map in docs/FEATURES.md is stale: run python3 tools/generate_settings_map.py")
        problems += check_paths(model)
        for p in problems:
            print(p)
        sys.exit(1 if problems else 0)
    FEATURES.write_text(text.replace(current, section), encoding="utf-8")
    print("settings map updated")


if __name__ == "__main__":
    main()
